import { Controller } from "@hotwired/stimulus"
import { newFormUrl, submissionClosesModal } from "meeting_modal"
import { trapTabKey } from "dialog_a11y"

/**
 * Meeting Modal Controller
 *
 * "Neues Meeting" on the org-wide meetings list. A meeting always belongs to a
 * project, so the modal asks for one first and then loads the real form for it.
 *
 * Every <option> carries its own new-URL from ERB; this controller only copies that
 * value onto the frame's src, after adding the state the list shows RIGHT NOW
 * (lib/meeting_modal.js). Nothing here knows how a meetings route is spelled, so
 * a route change cannot silently break the modal.
 *
 * Shape and lifecycle follow docs/dokumentation/modal_pattern.md, which names this
 * controller its reference implementation; the focus trap is the shared
 * lib/dialog_a11y.js the help modal and the drawers already use.
 */
export default class extends Controller {
  static targets = ["modal", "frame", "projectSelect", "card"]
  // listFrame: the id of the overview's list frame. It lives OUTSIDE this
  // controller's element (the title box), so it cannot be a Stimulus target; the
  // id travels from ERB rather than being hard-coded here.
  static values = { listFrame: String }

  connect() {
    this.modalTarget.classList.add("hidden")
    // The zero state ("choose a project first"), restored on every close.
    this.placeholderHTML = this.frameTarget.innerHTML
    this.lastFocused = null

    this.handleTurboSuccess = this.handleTurboSuccess.bind(this)
    this.handleFrameLoad = this.handleFrameLoad.bind(this)
    document.addEventListener("turbo:submit-end", this.handleTurboSuccess)
    this.frameTarget.addEventListener("turbo:frame-load", this.handleFrameLoad)
  }

  disconnect() {
    document.removeEventListener("turbo:submit-end", this.handleTurboSuccess)
    this.frameTarget.removeEventListener("turbo:frame-load", this.handleFrameLoad)
    // The element can be removed while the modal is open (a stream replacing the
    // header, a morph). Leaving the scroll lock behind would freeze the page.
    document.body.classList.remove("overflow-hidden")
  }

  /**
   * A successful save answers with turbo-streams that refresh the list behind the
   * modal; closing is left to us. Membership is checked instead of a form id: the id
   * is generated by form_with and would tie this controller to that detail.
   *
   * detail.success alone is NOT enough: fetch follows redirects, so the area gate's
   * redirect_to answers 200 and would read as a save that never happened.
   */
  handleTurboSuccess(event) {
    const form = event.target
    if (!form || !this.element.contains(form)) return

    if (submissionClosesModal(event.detail)) this.close()
  }

  /**
   * A frame answer that arrived after we stopped wanting it. Turbo cancels a frame
   * fetch only when a NEW visit starts, and removing src starts none, so a load in
   * flight when the modal closes still renders into the hidden frame. Without this
   * the next open shows a full form for the abandoned project while the select reads
   * "Projekt wählen …", and saving would file the meeting under that project.
   */
  handleFrameLoad() {
    if (this.projectSelectTarget.value) return

    this.resetFrame()
  }

  open() {
    this.lastFocused = document.activeElement
    this.modalTarget.classList.remove("hidden")
    document.body.classList.add("overflow-hidden")
    this.projectSelectTarget.focus()
  }

  /** Load the form for the chosen project; back to the zero state when cleared. */
  projectChanged() {
    const option = this.projectSelectTarget.selectedOptions[0]
    const url = newFormUrl(option && option.dataset.newUrl, this.currentListQuery())

    if (!url) {
      this.resetFrame()
      return
    }

    this.frameTarget.setAttribute("src", url)
  }

  /**
   * The state the list shows at this moment, NOT the one when ERB rendered the
   * options: the list frame writes it at every load, the page is never re-rendered
   * when a filter, a sort or a page changes.
   */
  currentListQuery() {
    const frame = this.hasListFrameValue ? document.getElementById(this.listFrameValue) : null
    const state = frame && frame.querySelector("[data-list-filter-query]")
    return state ? state.dataset.listFilterQuery : ""
  }

  close() {
    this.modalTarget.classList.add("hidden")
    document.body.classList.remove("overflow-hidden")

    // A closed modal reopens empty: the next meeting is a new decision, and a
    // half-filled form for a project chosen minutes ago is a trap.
    this.projectSelectTarget.value = ""
    this.resetFrame()

    if (this.lastFocused && typeof this.lastFocused.focus === "function") this.lastFocused.focus()
    this.lastFocused = null
  }

  resetFrame() {
    this.frameTarget.removeAttribute("src")
    this.frameTarget.innerHTML = this.placeholderHTML
  }

  closeOnBackdrop(event) {
    if (event.target === event.currentTarget) {
      this.close()
    }
  }

  closeOnEscape(event) {
    if (event.key === "Escape" && this.isOpen) {
      this.close()
    }
  }

  /** Keyboard must not wander into the page behind an aria-modal dialog. */
  trapFocus(event) {
    if (!this.isOpen) return

    trapTabKey(event, this.cardTarget)
  }

  get isOpen() {
    return !this.modalTarget.classList.contains("hidden")
  }
}
